class TestMorphology(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.morph = make_morph()

    def test_pair_count_meets_spec(self):
        self.assertGreaterEqual(len(RULE_PAIRS) + len(DICT_PAIRS), 100)

    def test_rule_pairs(self):
        failures = []
        for surface, expected in RULE_PAIRS:
            got = self.morph.lemmatize(surface)
            if got != expected:
                failures.append(f"{surface} -> {got!r} (expected {expected!r})")
        self.assertEqual(failures, [], f"{len(failures)} of {len(RULE_PAIRS)} failed")

    def test_dict_pairs(self):
        for surface, expected in DICT_PAIRS:
            self.assertEqual(self.morph.lemmatize(surface), expected)

    def test_identity_for_vocab_words(self):
        for w in ["ном", "хот", "морь", "сургууль"]:
            self.assertEqual(self.morph.lemmatize(w), w)

    def test_acceptance_case_forms_of_nokhoi_agree(self):
        """Spec §12: нохойн/нохойд/нохойг/НОХОЙ/' нохой ' all resolve identically."""
        targets = {
            self.morph.lemmatize(s)
            for s in ("нохойн", "нохойд", "нохойг", "НОХОЙ", " нохой ")
        }
        self.assertEqual(targets, {"нохой"})

    def test_inflected_answer_counts_as_lemma(self):
        """Guessing the answer in an inflected form resolves to its lemma."""
        self.assertEqual(self.morph.lemmatize("моригоо"), "морь")

    def test_unknown_words_return_none(self):
        for junk in ("зочин", "бббб", "х", "", "123"):
            self.assertIsNone(self.morph.lemmatize(junk), junk)

    def test_all_candidates_includes_multiple_parses_when_ambiguous(self):
        cands = self.morph.all_candidates("модонд")
        self.assertIn("мод", cands)


